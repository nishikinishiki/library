本人の属性によっても異なるものの、リノベーション物件またはリノベーションを前提とした築古物件の購入は、銀行融資を受けるのが簡単ではありません。前者の場合、室内は新築同様だとしても、建物自体が築古であれば、新築として扱えないため、銀行の担保評価には厳しい目が向けられ、融資審査通過は容易ではありません。また、後者の築古物件を購入して、それからリノベーションを行う計画の場合、まず、築古物件の融資が難しいのに加え、その後の改築も費用対効果などあらゆる面から検証されます。そのため大部分を借り入れではなく、自己資金で支払う必要があるでしょう。よほどの高収入であるなどの属性の高さがある場合を除き、支払う費用の大半を金融機関から調達するのは難しいかもしれません。

